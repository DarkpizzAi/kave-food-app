/* Spoon: Receipt data clean-up (Prices tab, after Trends).

   Three numbers and a Clean up button. The button opens a sheet of cards, one
   per receipt product from the last 30 days that has something missing or
   doubtful. Answering a card uploads one small file to
   food/data/cleanup-answers/ in kave-hub; nothing else changes. A person
   reviews and applies those files later (apply_cleanup_answers.py), which is
   also when the card is deleted for good.

   Until then an answer can be undone from the Decisions tab, which deletes the
   file and brings the card back. After that the file is gone, so Undo finds
   nothing and says so. The queue itself is regenerated by build_cleanup_queue.py
   and only ever holds cards from the last 30 days. */
